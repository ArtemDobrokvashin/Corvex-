package ru.corvex.admin.rbac;

/**
 * Каталог прав Corvex. Право — атомарная строка-код; группы в админке собирают права
 * чекбоксами, эффективные права пользователя = объединение прав всех его групп
 * (см. EffectivePermissionService). Коды стабильны: переименование = миграция данных,
 * поэтому человекочитаемые подписи для UI лежат в i18n-бандле фронтенда, а не здесь.
 */
public enum Permission {

    // --- Почта ---
    MAIL_READ_OWN,          // читать свою почту
    MAIL_SEND_INTERNAL,     // отправлять внутри доменов компании
    MAIL_SEND_EXTERNAL,     // отправлять во внешние домены
    MAIL_MANAGE_FOLDERS,    // создавать папки/правила сортировки
    MAIL_BULK_SEND,         // массовые рассылки (бухгалтерия, HR)
    MAIL_DELEGATE_ACCESS,   // делегированный доступ к чужому ящику (секретарь директора)
    MAIL_EXPORT,            // экспорт ящика (eml/mbox)

    // --- Чат ---
    CHAT_READ,
    CHAT_WRITE,
    CHAT_CREATE_GROUP,      // создавать групповые чаты
    CHAT_CREATE_CHANNEL,    // создавать каналы (по умолчанию — только админы)
    CHAT_MODERATE,          // удалять/закреплять чужие сообщения в модерируемых каналах
    CHAT_SEND_FILES,
    CHAT_VOICE_VIDEO,       // голосовые/видеосообщения

    // --- Администрирование ---
    ADMIN_USERS_MANAGE,     // CRUD пользователей, блокировка
    ADMIN_GROUPS_MANAGE,    // группы и их права
    ADMIN_QUOTAS_MANAGE,    // дисковые квоты
    ADMIN_SECURITY_POLICY,  // пароли, 2FA, сессии
    ADMIN_MAIL_POLICY,      // спам/антивирус, лимиты вложений, домены
    ADMIN_SERVER_CONFIG,    // настройки сервера, сертификаты (только суперадмин)
    ADMIN_BACKUP,           // резервное копирование/восстановление

    // --- Аналитика и аудит (не дают доступа к содержимому чужих писем/чатов!) ---
    ANALYTICS_VIEW_OWN_UNIT, // активность своего подразделения (руководитель)
    ANALYTICS_VIEW_COMPANY,  // отчёты по компании (директор)
    AUDIT_VIEW               // журнал аудита
}
